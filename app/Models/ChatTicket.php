// ChatService::handleTicketAssignment: نفس الفكرة (إنشاء/إعادة فتح + تعيين تلقائي)، لكنها دالة داخل الخدمة وكانت تُستدعى من نسخ قديمة من الـ Webhook. التدفق الحالي يعتمد على الـ Job وليس على هذه الدالة في الـ Webhook الرئيسي.
// كلاهما يخدم نفس الهدف: "عند وصول رسالة، تأكد من وجود تذكرة مفتوحة ومعيّنة (أو غير معينة) حسب الإعدادات".
// 9. ملخص سريع: لماذا نحتاج Chat Ticket؟
// بدون تذاكر: قائمة واحدة طويلة، لا مسؤول واضح، لا حالة (مفتوحة/مغلقة)، لا توزيع منظم.
// مع تذاكر:
// كل محادثة = تذكرة (حالة + وكيل).
// توزيع تلقائي أو يدوي.
// فلترة (غير معينة، مفتوحة، مغلقة، معينة لي).
// سجل أحداث داخل الخيط (فتح، إغلاق، تعيين، إعادة فتح).
// صلاحيات (الوكيل يرى كل المحادثات أو فقط ما يخصه).
// مثال واقعي واحد يجمع كل شيء:
// عميل يرسل → تذكرة تُفتح وتُعيَّن لسارة → سارة ترد وتُغلق التذكرة → العميل يرد لاحقاً → التذكرة تُفتح وقد تُعيَّن لمحمد → في الخيط تظهر كل الأحداث (فتح، تعيين، إغلاق، إعادة فتح). هذا هو نظام Chat Ticket بالكامل عملياً.

class ChatTicket extends Model {
    use HasFactory;

    protected $guarded = [];
    public $timestamps = false;

    protected static function booted(): void
    {
        // عند إنشاء تذكرة جديدة: هذه تكون الأحدث (is_latest = true) والباقي لنفس الـ contact = false
        static::created(function (ChatTicket $ticket) {
            DB::table('chat_tickets')
                ->where('contact_id', $ticket->contact_id)
                ->where('id', '!=', $ticket->id)
                ->update(['is_latest' => false]);
            DB::table('chat_tickets')
                ->where('id', $ticket->id)
                ->update(['is_latest' => true]);
        });

        // عند حذف تذكرة كانت الأحدث: جعل التذكرة التالية (أعلى id المتبقية) هي الأحدث
        static::deleting(function (ChatTicket $ticket) {
            if (!$ticket->is_latest) {
                return;
            }
            $nextId = DB::table('chat_tickets')
                ->where('contact_id', $ticket->contact_id)
                ->where('id', '!=', $ticket->id)
                ->orderByDesc('id')
                ->value('id');
            if ($nextId !== null) {
                DB::table('chat_tickets')->where('id', $nextId)->update(['is_latest' => true]);
            }
        });
    }

    public function getCreatedAtAttribute($value)
    {
        return DateTimeHelper::convertToOrganizationTimezone($value)->toDateTimeString();
    }

    public function getUpdatedAtAttribute($value)
    {
        return DateTimeHelper::convertToOrganizationTimezone($value)->toDateTimeString();
    }

    public function user(){
        return $this->belongsTo(User::class, 'assigned_to', 'id');
    }
}
