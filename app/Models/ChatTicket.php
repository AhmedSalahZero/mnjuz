// 6. أين يظهر كل شيء في التطبيق؟
// ما يحدث	أين يظهر للمستخدم
// تذكرة جديدة (فتح محادثة)	حدث في خيط المحادثة: "Conversation was opened" + ظهور المحادثة في القائمة (معينة أو غير معينة).
// تعيين تذكرة لوكيل	حدث في الخيط: "Conversation was assigned to ..." + ظهور المحادثة في قائمة ذلك الوكيل.
// إغلاق تذكرة	حدث في الخيط: "Conversation was moved from open to closed" + إمكانية فلترة "مغلقة".
