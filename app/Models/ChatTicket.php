// العمود	المعنى
// contact_id	نفس جهة الاتصال.
// description	نص الحدث، مثل: "Conversation was opened" أو "Conversation was assigned to سارة".
// هذه الأحداث تظهر داخل خيط المحادثة كأسطر بين الرسائل (مثلاً: "تم تعيين المحادثة لسارة"، "تم إغلاق التذكرة").
// لماذا نحتاجها؟
// للمراجعة والشفافية: متى فُتحت التذكرة، من عيّنها، متى أُغلقت، متى أُعيد فتحها. بدونها تعرف الحالة الحالية فقط ولا تعرف التاريخ.
// 4. الإعدادات (ماذا تفعل كل واحدة؟)
// كلها مخزنة في إعدادات المنظمة (Organization) تحت مفتاح tickets:
// 1) تفعيل التذاكر (active)
// معناها: تشغيل أو إيقاف نظام التذاكر بالكامل.
// مثال:
// عندك 3 وكلاء وتريد توزيع المحادثات وتتبعها → تفعّل. لو كنت وحدك ولا تحتاج توزيعاً → يمكن إيقافها وتكون كل المحادثات "قائمة واحدة" بدون تعيين أو حالة.
// 2) التعيين التلقائي (auto_assignment)
// معناها: عند وصول رسالة جديدة (أو إعادة فتح تذكرة مغلقة)، هل نُعيِّن التذكرة تلقائياً لواحد من الوكلاء؟
// مثال:
// مفعّل: خالد يرسل رسالة → النظام يختار وكيلاً (مثلاً من لديه أقل عدد تذاكر مفتوحة) ويُعيِّن المحادثة له. معطّل: المحادثة تبقى "غير معينة" ويختار أحد الوكلاء يدوياً من قائمة "غير المعينة".
// 3) إعادة تعيين المحادثات المُعاد فتحها (reassign_reopened_chats)
// معناها: عندما يكون العميل قد أغلقتم تذكرته، ثم راسلكم مرة أخرى فتُفتح التذكرة من جديد، هل نُعيد تعيينها لوكيل جديد؟
// مثال:
// مفعّل: كانت المحادثة لسارة وأُغلقت. خالد يرسل مرة ثانية → التذكرة تُفتح وقد تُعيَّن لمحمد (حسب التعيين التلقائي). معطّل: تبقى معينة لسارة أو تصبح غير معينة حسب الإعدادات.
// 4) السماح للوكلاء برؤية كل المحادثات (allow_agents_to_view_all_chats)
// معناها: هل الوكيل يرى كل المحادثات أم فقط ما هو معيّن له + غير المعينة؟
// مثال:
// مفعّل: أحمد يرى قائمة فيها محادثات سارة ومحمد وكل شيء (للإشراف أو المساعدة). معطّل: أحمد يرى فقط "محادثاتي" + "غير المعينة" (حتى يختار منها)، ولا يرى محادثات سارة أو محمد.
// 5) تشفير أرقام الجهات للوكلاء (encrypt_contacts_for_agents)
// معناها: هل نُخفِي رقم هاتف العميل عن الوكلاء (مثلاً نعرض 05xxxxxxxx فقط)؟
// مثال:
// تريد حماية بيانات العملاء ولا تريد أن ينسخ الوكيل الرقم كاملاً → تفعّل. لو تريد الشفافية الكاملة للفريق → تعطّل.
// 5. التدفق خطوة بخطوة (مع أمثلة)
