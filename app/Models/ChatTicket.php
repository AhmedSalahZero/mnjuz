// شرح نظام Chat Ticket بالتفصيل مع أمثلة واقعية
// 1. ما هو Chat Ticket؟ (بجملة واحدة)
// Chat Ticket = "تذكرة محادثة": كل محادثة واتساب مع جهة اتصال (عميل) تُعامل كـ تذكرة واحدة لها حالة (مفتوحة/مغلقة) ووكيل معيّن (من فريقك)، ويمكن توزيعها وفلترتها وتتبعها.
// 2. لماذا نحتاجه أصلاً؟ (المشكلة والحل)
// المشكلة بدون نظام تذاكر
// تخيل أنك تملك متجراً إلكترونياً وفريق دعم من 3 أشخاص (سارة، أحمد، محمد). الواتساب يأتيكم من عشرات العملاء يومياً:
// بدون تذاكر:
// الجميع يرى نفس القائمة الطويلة من المحادثات. لا تعرف من يرد على من، من أنهى المحادثة ومن لم ينهِها، ومن "أخذ" المحادثة. النتيجة: ردود مكررة، محادثات تضيع، عملاء ينتظرون ولا أحد يعرف المسؤول.
// الحل مع نظام Chat Ticket
// كل محادثة = تذكرة واحدة مرتبطة بجهة اتصال (العميل).
// كل تذكرة لها:
// حالة: مفتوحة (قيد المتابعة) أو مغلقة (انتهى التعامل).
// وكيل معيّن: شخص واحد مسؤول عن الرد (سارة أو أحمد أو محمد)، أو "غير معينة" حتى يختار أحدهم المحادثة.
// يمكن:
// توزيع المحادثات على الفريق (يدوياً أو تلقائياً).
// فلترة القائمة: "المحادثات المفتوحة"، "غير المعينة"، "المغلقة"، "المعينة لي".
// تتبع من فتح التذكرة، من أغلقها، ومن عيّنها لمن.
// مثال واقعي:
// عميل "خالد" يرسل: "أين طلبي؟". النظام يفتح تذكرة ويُعيِّنها تلقائياً لـ "سارة" (لأن لديها أقل عدد تذاكر مفتوحة). سارة ترد وتُنهي الموضوع وتضغط "إغلاق التذكرة". لو خالد راسل مرة ثانية، النظام يعيد فتح التذكرة وقد يعيد تعيينها لوكيل آخر حسب الإعدادات. بدون هذا النظام لا يوجد "تذكرة" أصلاً، فقط قائمة محادثات بدون مسؤول واضح أو حالة.
// 3. المكونات الأساسية (جدول + حالة + وكيل)
// أ) جدول chat_tickets
// كل صف = تذكرة واحدة لمحادثة واحدة (مرتبطة بجهة اتصال واحدة):
