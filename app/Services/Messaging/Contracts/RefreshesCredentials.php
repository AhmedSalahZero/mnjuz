<?php

namespace App\Services\Messaging\Contracts;

use App\Models\ChannelAccount;

/**
 * تُنفّذها المنصّات التي تنتهي صلاحية توكناتها دورياً.
 *
 * واجهة مستقلّة لا طريقة في ChannelDriver: تيك توك وحدها تحتاجها اليوم،
 * وإقحامها في العقد العامّ يُجبر أربعة سائقين على كتابة دالّة فارغة —
 * والدالّة الفارغة تُخفي السؤال «هل هذه القناة تحتاج تجديداً؟» بدل أن
 * تُجيب عنه.
 */
interface RefreshesCredentials
{
    /**
     * تجديد التوكن إن لزم.
     *
     * $leewayMinutes هو الهامش الذي نعدّ التوكن معه «موشكاً على الانتهاء».
     * مسار الإرسال يستعمل هامشاً صغيراً — لا يُجدّد إلّا عند الحاجة —
     * والمهمّة المجدولة تستعمل هامشاً أوسع لتُجدّد استباقاً قبل أن ينقطع
     * شيء. وبلا هذا المعامل كانت المهمّة تختار حساباً ثم يردّ السائق
     * «ما زال صالحاً» فلا يُجدَّد أبداً.
     *
     * @return bool  نجح التجديد أو لم يكن لازماً
     */
    public function refreshCredentials(ChannelAccount $account, int $leewayMinutes = 5): bool;
}
