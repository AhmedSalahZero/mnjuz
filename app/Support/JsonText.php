<?php

namespace App\Support;

/**
 * ترميز JSON بالنصّ العربي خاماً بدل \uXXXX.
 *
 * json_encode في PHP يهرّب كل حرف غير ASCII افتراضياً منذ 5.2، فالحرف العربي
 * يشغل ستّة بايتات (ا) بدل اثنين. وحين يوضع الناتج كنصّ داخل ردّ JSON
 * آخر تُهرَّب الشرطة المائلة نفسها فيصير سبعة — ثلاثة أضعاف ونصف.
 *
 * قِسنا الأثر على المنشأة 211: حقل metadata وحده 23.21 ميغابايت من ردٍّ حجمه
 * 39.73، ينزل إلى 10.29 بالترميز الخام.
 *
 * المسار كلّه UTF-8 — الأعمدة utf8mb4، والردود بـ charset=utf-8، والعملاء
 * يفكّون JSON — فلا مبرّر للتهريب. والصيغتان متكافئتان في معيار JSON:
 * "ا" و"ا" ينتجان النصّ نفسه عند أي مُحلِّل، في أي لغة.
 */
final class JsonText
{
    /** الرايات المعتمدة لكل JSON نكتبه في قاعدة البيانات أو نرسله للعميل. */
    public const FLAGS = JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES;

    /**
     * بديل مباشر لـ json_encode بنفس التوقيع والسلوك، عدا أنه لا يهرّب
     * العربية ولا الشرطة المائلة.
     *
     * @return string|false نفس ما يُرجعه json_encode عند الفشل.
     */
    public static function encode(mixed $value, int $extraFlags = 0)
    {
        return json_encode($value, self::FLAGS | $extraFlags);
    }

    /**
     * إعادة ترميز نصّ JSON مخزَّن إلى الصيغة الخام — أو null إن تعذّر إثبات
     * أن التحويل لا يفقد شيئاً.
     *
     * الشرط الذي نفرضه: أن تُعيد دورةُ (فكّ ← ترميز بالرايات الافتراضية)
     * النصَّ الأصلي بايتاً ببايت. اجتيازها برهانٌ على أن الفكّ لم يُسقط شيئاً:
     * لا دقّة عدد كبير تجاوز PHP_INT_MAX فصار float، ولا تمييزاً بين {} و[]،
     * ولا ترتيب مفاتيح، ولا كسراً عشرياً. وعندها فقط يصحّ أن نكتب الصيغة
     * الخام مكانه، لأن الفرق الوحيد الباقي بين النصّين هو التهريب.
     *
     * وأي صفّ لا يجتاز الشرط يُترك كما هو — لا يُمَسّ ولا يُفقد.
     *
     * قِسنا الشرط على عيّنة 30 ألف صفّ من الإنتاج: اجتازها 98.6%، والصفوف
     * المتخطّاة تختلف بمسافات الترقيم فقط (كتبها مُنتِج آخر بـ ", " بدل ",")
     * ولا يحوي أيٌّ منها تهريباً أصلاً — أي أن الشرط الصارم لا يضيّع بايتاً
     * واحداً كان يمكن توفيره.
     *
     * @return string|null الصيغة الخام، أو null إذا تعذّر الإثبات أو لا جديد.
     */
    public static function reencodeLossless(string $json): ?string
    {
        if ($json === '') {
            return null;
        }

        // الفكّ في وضع الكائنات لا المصفوفات: هو وحده ما يحفظ الفرق بين
        // {} و[]، وفكّه assoc يخلطهما فيخرج "[]" مكان "{}".
        $decoded = json_decode($json);
        if (json_last_error() !== JSON_ERROR_NONE) {
            return null;
        }

        if (json_encode($decoded) !== $json) {
            return null;
        }

        $raw = self::encode($decoded);
        if ($raw === false || $raw === $json) {
            return null;
        }

        return $raw;
    }
}
